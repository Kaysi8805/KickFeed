const namedByTeam = new Map<string, Player[]>();
for (const [teamId, rows] of Object.entries(NAMED_SQUADS)) {
  namedByTeam.set(teamId, toPlayers(teamId, uniqueNumbers(teamId, rows)));
}

function uniqueNumbers(teamId: string, rows: Row[]): Row[] {
  const seen = new Set<number>();
  const out: Row[] = [];
  for (const row of rows) {
    if (seen.has(row[0])) {
      throw new Error(`Duplicate squad number ${row[0]} on ${teamId} (${row[2]})`);
    }
    seen.add(row[0]);
    out.push(row);
  }
  return out;
}

function generatedSquad(teamId: string): Player[] {
  const seed = hash(teamId);
  return GEN_NUMBERS.map((number, i) => {
    const n = seed + i * 17;
    return {
      id: playerIdFor(teamId, number),
      name: `${FIRST[n % FIRST.length]} ${LAST[(n + 3) % LAST.length]}`,
      shortName: LAST[(n + 3) % LAST.length],
      teamId,
      number,
      pos: GEN_POS[i],
      nationality: NATS[n % NATS.length],
      age: 21 + (n % 14),
    };
  });
}

