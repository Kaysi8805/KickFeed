function hash(s: string): number {
  let n = 0;
  for (let i = 0; i < s.length; i += 1) n = (n * 31 + s.charCodeAt(i)) >>> 0;
  return n;
}

export function foldName(s: string): string {
  return s
    .normalize('NFD')
    .replace(/\p{M}/gu, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

export function playerIdFor(teamId: string, number: number): string {
  return `p-${teamId}-${number}`;
}

function toPlayers(teamId: string, rows: Row[]): Player[] {
  return rows.map(([number, pos, name, shortName, nationality, age]) => ({
    id: playerIdFor(teamId, number),
    name,
    shortName,
    teamId,
    number,
    pos,
    nationality,
    age,
  }));
}

